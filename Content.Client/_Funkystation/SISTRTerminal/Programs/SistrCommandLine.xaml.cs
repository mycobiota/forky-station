using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._Funkystation.SISTRTerminal.Programs;

[GenerateTypedNameReferences]
public sealed partial class SistrCommandLine : BoxContainer
{
    public Action<string[]>? RunProgram;

    // todo: better way of defining commands
    private readonly Dictionary<string, Action<string[]>> _commands = new ();

    public SistrCommandLine()
    {
        RobustXamlLoader.Load(this);

        TerminalLineInput.OnTextEntered += args =>
        {
            TerminalLineInput.Clear();
            AddLine($"> {args.Text}");
            ParseCommand(args.Text);
        };

        // todo: better way of defining commands?
        _commands.Add("clear", ClearTerminalCommand);
        _commands.Add("echo", EchoCommand);
        _commands.Add("run", RunProgramCommand);
    }

    public void AddLine(string message)
    {
        AddLineFormatted(FormattedMessage.FromUnformatted(message));
    }

    public void AddLineFormatted(FormattedMessage message)
    {
        TerminalOutput.AddMessage(message);
    }

    private void ParseCommand(string command)
    {
        var arguments = command.Split(' ');
        _commands.TryGetValue(arguments[0], out var action);
        action?.Invoke(arguments[1..]);
    }

    private void RunProgramCommand(string[] args)
    {
        RunProgram?.Invoke(args);
    }

    private void ClearTerminalCommand(string[] args)
    {
        TerminalOutput.Clear();
    }

    private void EchoCommand(string[] args)
    {
        var input = string.Join(' ', args);
        AddLine(input);
    }
}
