using Content.Client._Funkystation.SISTRTerminal.Programs;
using Content.Client.UserInterface.ControlExtensions;
using Content.Client.UserInterface.Controls;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Sandboxing;
using Robust.Shared.Utility;

namespace Content.Client._Funkystation.SISTRTerminal;

[GenerateTypedNameReferences]
public sealed partial class SistrTerminalUi : FancyWindow
{
    public SistrTerminalUi()
    {
        RobustXamlLoader.Load(this);
    }

    public void OpenProgram(ref SistrProgramControl program)
    {
        SistrCommandLine.Visible = false;
        InternalWindow.AddChild(program);
    }

    public void OnProgramClosed()
    {
        SistrCommandLine.Visible = true;
    }
}

public abstract class SistrProgramControl : BoxContainer
{
    public Action? ExitProgram;
}
